#!/usr/bin/env python3
"""Writes ../neonpine/anim_tables.h: lookup tables for the fixed-point animations (anim.c).

The CH32V003 has no FPU and no multiplier, so sin and exp come from tables (the noise hash is computed:
wang() in anim.c). The same values are in ../../companion/neonpine_companion/builtin.py.
Q12 = 4096 is 1.0. Rerun after changing anything here: python3 tools/gen_anim_tables.py
"""
import math
import os

Q = 4096
out = os.path.join(os.path.dirname(__file__), "..", "neonpine", "anim_tables.h")

sin_tab = [round(Q * math.sin(2 * math.pi * k / 256)) for k in range(65)]           # quarter turn, 256 steps per turn
exp2_tab = [round(Q * 2 ** (-k / 16)) for k in range(17)]                         # 2^-f, f = 0 .. 1 in 1/16 (expneg)


def rows(vals, per=16):
    return "\n".join("\t" + ", ".join(str(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per))


with open(out, "w") as f:
    f.write("// Generated by tools/gen_anim_tables.py - do not edit.\n#pragma once\n#include <stdint.h>\n\n")
    f.write("// sin(2 pi k / 256), Q12, first quarter (the rest by symmetry)\nstatic const uint16_t sin_tab[65] = {\n%s\n};\n\n" % rows(sin_tab))
    f.write("// 2^(-k / 16), Q12 (expneg: e^-x = 2^-(x log2 e))\nstatic const uint16_t exp2_tab[17] = {\n%s\n};\n" % rows(exp2_tab))
print("wrote", os.path.normpath(out))
